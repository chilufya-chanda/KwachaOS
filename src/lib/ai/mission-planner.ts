import { prisma } from "@/lib/database/prisma";
import {
  planMission,
  InsufficientBalanceError,
} from "@/lib/ai/gemini";

export { InsufficientBalanceError };

type RawMissionTask = {
  agentKey?: unknown;
  title?: unknown;
  instructions?: unknown;
  toolKeys?: unknown;
};

type NormalizedMissionTask = {
  agentKey: string;
  title: string;
  instructions: string;
  toolKeys: string[];
};

type NormalizedMissionPlan = {
  missionSummary: string;
  strategy: string;
  assumptions: string[];
  tasks: NormalizedMissionTask[];
};

function cleanString(
  value: unknown,
  fallback: string
): string {
  if (typeof value !== "string") {
    return fallback;
  }

  const cleaned = value.trim();

  return cleaned || fallback;
}

function cleanStringArray(
  value: unknown
): string[] {
  if (!Array.isArray(value)) {
    return [];
  }

  return value
    .filter((item): item is string => typeof item === "string")
    .map((item) => item.trim())
    .filter(Boolean);
}

function normalizeMissionPlan(
  raw: unknown
): NormalizedMissionPlan {
  if (!raw || typeof raw !== "object") {
    throw new Error(
      "Gemini returned an invalid mission plan."
    );
  }

  const candidate = raw as Record<string, unknown>;

  const rawTasks = Array.isArray(candidate.tasks)
    ? candidate.tasks
    : [];

  const tasks: NormalizedMissionTask[] = rawTasks
    .filter(
      (task): task is RawMissionTask =>
        !!task &&
        typeof task === "object"
    )
    .map((task, index) => {
      const agentKey = cleanString(
        task.agentKey,
        ""
      );

      const title = cleanString(
        task.title,
        `Mission task ${index + 1}`
      );

      const instructions = cleanString(
        task.instructions,
        `Execute the assigned mission task: ${title}`
      );

      const toolKeys = cleanStringArray(
        task.toolKeys
      );

      return {
        agentKey,
        title,
        instructions,
        toolKeys,
      };
    })
    .filter((task) => Boolean(task.agentKey));

  if (tasks.length === 0) {
    throw new Error(
      "Gemini returned a mission plan without any valid agent tasks."
    );
  }

  return {
    missionSummary: cleanString(
      candidate.missionSummary,
      "Mission execution plan generated by Kwacha OS."
    ),

    strategy: cleanString(
      candidate.strategy,
      "Execute the selected agent tasks in sequence and use their results to advance the mission."
    ),

    assumptions: cleanStringArray(
      candidate.assumptions
    ),

    tasks,
  };
}

export async function createMissionPlan(
  missionId: string
) {
  const mission = await prisma.mission.findUnique({
    where: {
      id: missionId,
    },

    include: {
      business: true,
    },
  });

  if (!mission) {
    throw new Error("Mission not found.");
  }

  if (!mission.business) {
    throw new Error(
      "This mission does not have a business attached."
    );
  }

  const rawPlan = await planMission(
    {
      businessName: mission.business.name,
      industry: mission.business.industry,
      location: mission.business.location,
      description: mission.business.description,
      targetMarket: mission.business.targetMarket,
      targetCustomers: mission.business.targetCustomers,
      objective: mission.objective,
      targetAudience: mission.targetAudience,
      budgetAmount: mission.budgetAmount,
      currency: mission.currency,
      deadline: mission.deadline.toISOString(),
      successMetric: mission.successMetric,
    },

    {
      workspaceId: mission.business.workspaceId,
      operation: "mission_planning",
    }
  );

  /*
   * Do not trust the model response blindly.
   *
   * Normalize it before touching the database.
   */
  const plan = normalizeMissionPlan(rawPlan);

  const agentKeys = [
    ...new Set(
      plan.tasks
        .map((task) => task.agentKey)
        .filter(Boolean)
    ),
  ];

  const agents = await prisma.agent.findMany({
    where: {
      key: {
        in: agentKeys,
      },
    },
  });

  const agentByKey = new Map(
    agents.map((agent) => [
      agent.key,
      agent,
    ])
  );

  const missingAgents = plan.tasks
    .filter(
      (task) => !agentByKey.has(task.agentKey)
    )
    .map((task) => task.agentKey);

  if (missingAgents.length > 0) {
    throw new Error(
      `Gemini selected agent(s) that are not registered in Kwacha OS: ${[
        ...new Set(missingAgents),
      ].join(", ")}`
    );
  }

  await prisma.$transaction(
    async (tx) => {
      /*
       * Remove only queued tasks from a previous
       * planning attempt. Never delete running or
       * completed work.
       */
      await tx.agentTask.deleteMany({
        where: {
          missionId: mission.id,
          status: "queued",
        },
      });

      for (const task of plan.tasks) {
        const agent = agentByKey.get(
          task.agentKey
        );

        if (!agent) {
          continue;
        }

        await tx.agentTask.create({
          data: {
            missionId: mission.id,
            agentId: agent.id,
            title: task.title,
            status: "queued",
          },
        });

        await tx.memory.create({
          data: {
            missionId: mission.id,

            key: `plan.${task.agentKey}`,

            value: JSON.stringify({
              instructions:
                task.instructions,

              toolKeys:
                task.toolKeys,
            }),
          },
        });
      }

      await tx.memory.create({
        data: {
          missionId: mission.id,

          key: "orchestrator.plan",

          value: JSON.stringify({
            summary:
              plan.missionSummary,

            strategy:
              plan.strategy,

            assumptions:
              plan.assumptions,
          }),
        },
      });

      await tx.activityLog.create({
        data: {
          missionId: mission.id,

          actor: "orchestrator",

          message:
            `AI generated a mission plan with ${plan.tasks.length} agent tasks.`,
        },
      });
    }
  );

  return plan;
}